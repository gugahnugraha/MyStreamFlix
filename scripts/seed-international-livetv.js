async function seedInternationalLiveTv() {
  console.log("\n📡 MyStreamFlix — International FTA Live TV Channel Seeder\n");
  console.log(`Seeding ${internationalChannels.length} international channels...\n`);

  for (const channel of internationalChannels) {
    await prisma.movie.upsert({
      where: { id: channel.id },
      update: channel,
      create: channel,
    });
    console.log(`  ✔ Seeded: ${channel.title} (${channel.country})`);
  }

  console.log(`\n🎉 Successfully seeded ${internationalChannels.length} International FTA Live TV Channels!\n`);
}

seedInternationalLiveTv()
  .catch((e) => {
    console.error("❌ Error seeding International Live TV channels:", e);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
